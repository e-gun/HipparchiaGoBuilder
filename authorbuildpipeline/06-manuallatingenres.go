func LoadLatinGenresIntoWorkMap() {
	keys := global.TheIdtWkMap.Keys()
	allworks := make([]structs.DbWork, len(keys))
	for i, key := range keys {
		widx, _ := global.TheIdtWkMap.Get(key)
		allworks[i] = widx
	}
	allworks = assignlatingenres(allworks)
	for _, work := range allworks {
		global.TheIdtWkMap.Set(work.UID, work)
	}
}

func assignlatingenres(wkk []structs.DbWork) []structs.DbWork {
	glines := strings.Split(GENRES, "\n")
	gmap := make(map[string]string)
	for _, g := range glines {
		kv := strings.Split(g, "·")
		gmap[kv[0]] = kv[1]
	}
	for i, w := range wkk {
		g, ok := gmap[w.UID]
		if ok {
			wkk[i].Genre = g
		}
	}
	return wkk
}

